#!/usr/bin/env python3
"""Render the shared Cybroid OS Xfce theme from common/branding/brand.toml.

Every target that ships Xfce (desktop ISO, server qcow2, pod-desktop) consumes
the output of this script. The version and all brand values come from the single
source of truth; no version or colour is hardcoded here.

Usage: render-xfce-brand.py --brand common/branding/brand.toml --out DIR
"""

from __future__ import annotations

import argparse
import html
import shlex
import shutil
import struct
import zlib
from pathlib import Path


def _png_chunk(kind: bytes, payload: bytes) -> bytes:
    return (
        struct.pack(">I", len(payload))
        + kind
        + payload
        + struct.pack(">I", zlib.crc32(kind + payload) & 0xFFFFFFFF)
    )


def solid_png(path: Path, color: str, width: int = 8, height: int = 8) -> None:
    """Write a tiny solid-colour PNG without external Python dependencies.

    xfwm4 window-decoration themes are image based; generating these from the
    brand palette keeps the decorations single-sourced without requiring
    ImageMagick/Pillow on every build host.
    """
    rgb = tuple(int(color[i : i + 2], 16) for i in (1, 3, 5))
    raw = b"".join(b"\x00" + bytes(rgb) * width for _ in range(height))
    ihdr = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    path.write_bytes(
        b"\x89PNG\r\n\x1a\n"
        + _png_chunk(b"IHDR", ihdr)
        + _png_chunk(b"IDAT", zlib.compress(raw, 9))
        + _png_chunk(b"IEND", b"")
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--brand", required=True, type=Path, help="path to brand.toml")
    parser.add_argument("--release", default="trixie", help="suite for the generated metadata")
    parser.add_argument("--out", required=True, type=Path, help="output directory")
    args = parser.parse_args()

    import tomllib

    data = tomllib.loads(args.brand.read_text(encoding="utf-8"))
    ident = data["identity"]
    colors = data["colors"]
    assets = data["assets"]

    name = ident["name"]
    version = ident["version"]  # single source of truth — never hardcode a version
    vendor = ident["vendor"]

    args.out.mkdir(parents=True, exist_ok=True)
    brand_root = args.brand.resolve().parent

    def esc(value: str) -> str:
        return html.escape(str(value), quote=True)

    # Brand values used by install.sh; shlex-quoted so shell sourcing is safe.
    env = {
        "PRODUCT_NAME": name,
        "PRODUCT_VERSION": version,
        "VENDOR_NAME": vendor,
        "BACKGROUND_COLOR": colors["background"],
        "PRIMARY_COLOR": colors["primary"],
        "ACCENT_COLOR": colors["accent"],
    }
    (args.out / "brand.env").write_text(
        "".join(f"{key}={shlex.quote(str(value))}\n" for key, value in env.items()),
        encoding="utf-8",
    )

    # Branded wallpaper shared by the whole Xfce look (also usable by Plasma).
    (args.out / "wallpaper.svg").write_text(
        f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/render-xfce-brand.py from {esc(args.brand.name)}. -->
<svg xmlns="http://www.w3.org/2000/svg" width="1920" height="1080" viewBox="0 0 1920 1080">
  <defs>
    <linearGradient id="cybroid-xfce-gradient" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="{esc(colors['primary'])}"/>
      <stop offset="0.55" stop-color="{esc(colors['primary_deep'])}"/>
      <stop offset="1" stop-color="{esc(colors['background'])}"/>
    </linearGradient>
    <linearGradient id="cybroid-xfce-rule" x1="0" y1="0" x2="1" y2="0">
      <stop offset="0" stop-color="{esc(colors['accent_alt'])}"/>
      <stop offset="1" stop-color="{esc(colors['accent'])}"/>
    </linearGradient>
  </defs>
  <rect width="1920" height="1080" fill="url(#cybroid-xfce-gradient)"/>
  <circle cx="1580" cy="210" r="420" fill="{esc(colors['accent'])}" opacity="0.10"/>
  <circle cx="280" cy="920" r="360" fill="{esc(colors['accent_alt'])}" opacity="0.10"/>
  <text x="960" y="500" text-anchor="middle" fill="{esc(colors['foreground'])}"
        font-family="sans-serif" font-size="110" letter-spacing="6">{esc(name)}</text>
  <rect x="660" y="552" width="600" height="8" rx="4" fill="url(#cybroid-xfce-rule)"/>
  <text x="960" y="620" text-anchor="middle" fill="{esc(colors['accent'])}"
        font-family="sans-serif" font-size="34">{esc(vendor)}</text>
  <text x="960" y="1000" text-anchor="middle" fill="{esc(colors['foreground'])}" opacity="0.7"
        font-family="sans-serif" font-size="22">{esc(ident['support_url'])}</text>
</svg>
""",
        encoding="utf-8",
    )

    (args.out / "xfce4-desktop.xml").write_text(
        """<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/render-xfce-brand.py from brand.toml. -->
<channel name="xfce4-desktop" version="1.0">
  <property name="backdrop" type="empty">
    <property name="screen0" type="empty">
      <property name="monitor0" type="empty">
        <property name="workspace0" type="empty">
          <property name="image-style" type="int" value="5"/>
          <property name="image-path" type="string" value="/usr/share/backgrounds/cybroidos/cybroidos-wallpaper.png"/>
          <property name="last-image" type="string" value="/usr/share/backgrounds/cybroidos/cybroidos-wallpaper.png"/>
        </property>
      </property>
    </property>
  </property>
</channel>
""",
        encoding="utf-8",
    )

    (args.out / "gtk.css").write_text(
        f"""/* Generated by tools/render-xfce-brand.py — {esc(name)} {esc(version)}. */
@import url("/usr/share/themes/Adwaita/gtk-3.0/gtk.css");

@define-color theme_selected_bg_color {esc(colors['accent'])};
@define-color theme_selected_fg_color {esc(colors['on_accent'])};
@define-color cybroid_primary {esc(colors['primary'])};
@define-color cybroid_accent {esc(colors['accent'])};

#cybroid-brand-bar {{
  background-color: @cybroid_primary;
  color: {esc(colors['foreground'])};
}}
""",
        encoding="utf-8",
    )

    # --- Custom panel layout -------------------------------------------------
    # Single top panel: branded applications menu, Cybroid app launchers,
    # task list, system tray, clock and show-desktop button.
    (args.out / "xfce4-panel.xml").write_text(
        f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/render-xfce-brand.py — {esc(name)} {esc(version)} custom panel. -->
<channel name="xfce4-panel" version="1.0">
  <property name="panels" type="array">
    <value type="int" value="1"/>
    <property name="panel-1" type="empty">
      <property name="position" type="string" value="p=0;x=0;y=0"/>
      <property name="length" type="string" value="0"/>
      <property name="position-locked" type="bool" value="true"/>
      <property name="size" type="uint" value="40"/>
      <property name="plugin-ids" type="array">
        <value type="int" value="1"/>
        <value type="int" value="2"/>
        <value type="int" value="3"/>
        <value type="int" value="4"/>
        <value type="int" value="5"/>
        <value type="int" value="6"/>
      </property>
    </property>
  </property>
  <property name="plugins" type="empty">
    <property name="plugin-1" type="string" value="applicationsmenu"/>
    <property name="plugin-2" type="string" value="launcher">
      <property name="items" type="array">
        <value type="string" value="cybroidos-browser.desktop"/>
        <value type="string" value="cybroidos-files.desktop"/>
        <value type="string" value="cybroidos-terminal.desktop"/>
        <value type="string" value="cybroidos-control.desktop"/>
      </property>
    </property>
    <property name="plugin-3" type="string" value="tasklist"/>
    <property name="plugin-4" type="string" value="systray"/>
    <property name="plugin-5" type="string" value="clock"/>
    <property name="plugin-6" type="string" value="showdesktop"/>
  </property>
</channel>
""",
        encoding="utf-8",
    )

    (args.out / "xfwm4.xml").write_text(
        f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/render-xfce-brand.py — branded window decorations. -->
<channel name="xfwm4" version="1.0">
  <property name="general" type="empty">
    <property name="theme" type="string" value="CybroidOS"/>
    <property name="title_align" type="int" value="0"/>
    <property name="use_compositing" type="bool" value="false"/>
  </property>
</channel>
""",
        encoding="utf-8",
    )

    # --- Custom applications -------------------------------------------------
    icon_path = "/usr/share/cybroidos/branding/cybroid-icon-64.png"
    launchers = {
        # The browser launcher uses xdg-open so it works with whichever browser
        # the user/installer provides, and opens the brand's own site by default.
        "cybroidos-browser.desktop": (
            f"{esc(name)} Browser",
            f"xdg-open {esc(ident['support_url'])}",
            "Network;WebBrowser;",
        ),
        "cybroidos-files.desktop": (
            f"{esc(name)} Files",
            "thunar %U",
            "System;FileManager;",
        ),
        "cybroidos-terminal.desktop": (
            f"{esc(name)} Terminal",
            "xfce4-terminal",
            "System;TerminalEmulator;",
        ),
        "cybroidos-control.desktop": (
            f"{esc(name)} Control",
            "/usr/bin/cybroidos-control list-actions",
            "System;Utility;",
        ),
    }
    for filename, (title, exec_line, categories) in launchers.items():
        (args.out / filename).write_text(
            f"""[Desktop Entry]
Type=Application
Version={esc(version)}
Name={title}
Comment={esc(vendor)} application
Exec={exec_line}
Icon={icon_path}
Terminal={'true' if 'control' in filename else 'false'}
Categories={categories}
StartupNotify=true
""",
            encoding="utf-8",
        )

    # --- Window decoration theme (xfwm4) ------------------------------------
    # Generated as small solid-colour PNGs so the brand palette drives the
    # title bars and borders without requiring image tooling on the build host.
    theme_dir = args.out / "xfwm4-theme"
    theme_dir.mkdir(exist_ok=True)
    (theme_dir / "theme.rc").write_text(
        f"""[general]
name=CybroidOS
version=1.0

[colors]
active_text_color={esc(colors['foreground'])}
inactive_text_color={esc(colors['accent'])}
""",
        encoding="utf-8",
    )
    deco_colors = {
        "title-active-left": colors["primary"],
        "title-active-middle": colors["primary"],
        "title-active-right": colors["primary"],
        "title-inactive-left": colors["primary_deep"],
        "title-inactive-middle": colors["primary_deep"],
        "title-inactive-right": colors["primary_deep"],
        "button-active": colors["accent"],
        "button-inactive": colors["primary"],
        "button-pressed": colors["accent_alt"],
        "button-hover": colors["accent_alt"],
        "border-active-left": colors["primary_deep"],
        "border-active-right": colors["primary_deep"],
        "border-active-bottom": colors["primary_deep"],
        "border-inactive-left": colors["background"],
        "border-inactive-right": colors["background"],
        "border-inactive-bottom": colors["background"],
    }
    for stem, color in deco_colors.items():
        solid_png(theme_dir / f"{stem}.png", color)

    (args.out / "cybroidos-xfce.desktop").write_text(
        f"""[Desktop Entry]
Type=Application
Name={esc(name)} Xfce
Comment=Branded Xfce session for {esc(name)} {esc(version)}
Exec=/usr/bin/cybroidos-xfce-session
TryExec=/usr/bin/startxfce4
DesktopNames=XFCE
X-LightDM-DesktopName={esc(name)} Xfce
X-KDE-PluginInfo-Version={esc(version)}
""",
        encoding="utf-8",
    )

    media = {
        "CYBROID_MEDIA_PROFILE": "1",
        "USE_COMPOSITING": "false",
        "DISABLE_SCREENSAVER": "true",
        "XFCE_SESSION_BIN": "/usr/bin/startxfce4",
        "X11VNC_EXTRA_ARGS": "-nowf -ncache 10 -ncache_cr",
    }
    (args.out / "xfce-media.conf").write_text(
        f"# Generated from brand.toml by tools/render-xfce-brand.py "
        f"({esc(name)} {esc(version)} / {esc(args.release)}).\n"
        + "".join(f"{key}={shlex.quote(str(value))}\n" for key, value in media.items()),
        encoding="utf-8",
    )

    # Static helpers live beside the brand source so they are versioned with it.
    static_root = Path(__file__).resolve().parent.parent / "common" / "branding" / "xfce"
    for helper in ("install.sh", "xfce-session-wrapper"):
        source = static_root / helper
        if not source.is_file():
            raise SystemExit(f"missing Xfce helper: {source}")
        shutil.copy2(source, args.out / helper)
        (args.out / helper).chmod(0o755)

    for key, target_name in (("logo_png", "logo.png"), ("mark_png", "mark.png")):
        source = brand_root / assets[key]
        if not source.is_file():
            raise SystemExit(f"missing brand asset: {source}")
        shutil.copy2(source, args.out / target_name)

    print(f"rendered Xfce branding into {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
