#!/usr/bin/env bash
# Apply rendered Cybroid OS branding to the server/pods rootfs.
#
# Usage: apply-branding.sh ROOTFS RENDER_DIR REPO_ROOT CONFIG_DIR
# RENDER_DIR is produced by tools/render-brand.py; CONFIG_DIR is
# targets/server/config. Every input is checked before anything is copied.
set -euo pipefail

die() { printf 'error: %s\n' "$*" >&2; exit 1; }

[ "$#" -eq 4 ] || die "usage: $0 ROOTFS RENDER_DIR REPO_ROOT CONFIG_DIR"
rootfs="$1"; render_dir="$2"; repo_root="$3"; config_dir="$4"
[ -d "${rootfs}" ] || die "rootfs not found: ${rootfs}"
[ -d "${render_dir}" ] || die "rendered branding directory not found: ${render_dir}"
[ -f "${render_dir}/usr/lib/os-release" ] || die "rendered os-release missing in ${render_dir}"
[ -f "${render_dir}/etc/motd" ] || die "rendered motd missing in ${render_dir}"
[ -f "${render_dir}/etc/issue" ] || die "rendered issue missing in ${render_dir}"
[ -d "${repo_root}/common/branding/logo" ] || die "brand logo directory missing"
grep -q '^ID=cybroidos$' "${render_dir}/usr/lib/os-release" \
	|| die "rendered os-release has no ID=cybroidos"

echo "Applying rendered branding to ${rootfs}"
cp -a "${render_dir}/." "${rootfs}/"

# --- Brand assets: wallpaper + Plymouth splash ------------------------------
logo_png="${repo_root}/common/branding/logo/cybroid-logo.png"
mark_png="${repo_root}/common/branding/logo/cybroid-mark.png"
[ -f "${logo_png}" ] || die "missing logo asset: ${logo_png}"
[ -f "${mark_png}" ] || die "missing mark asset: ${mark_png}"

wall_dir="${rootfs}/usr/share/backgrounds/cybroidos"
wallpaper="${wall_dir}/cybroidos-wallpaper.png"
mkdir -p "${wall_dir}"
bg="$(python3 - "${repo_root}/common/branding/brand.toml" <<'PY'
import sys, tomllib
with open(sys.argv[1], "rb") as fh:
    print(tomllib.load(fh)["colors"]["primary_deep"])
PY
)"
if command -v magick >/dev/null 2>&1; then
	magick -size 1920x1080 "xc:${bg}" "${logo_png}" -gravity center -composite "${wallpaper}"
elif command -v convert >/dev/null 2>&1; then
	convert -size 1920x1080 "xc:${bg}" "${logo_png}" -gravity center -composite "${wallpaper}"
else
	# No ImageMagick: use the brand mark itself as the wallpaper image.
	note="ImageMagick not installed; using the brand mark as wallpaper"
	printf '%s\n' "${note}" >&2
	cp "${mark_png}" "${wallpaper}"
fi

plymouth_theme="${rootfs}/usr/share/plymouth/themes/cybroidos"
mkdir -p "${plymouth_theme}"
cp "${mark_png}" "${plymouth_theme}/logo.png"
if [ -x "${rootfs}/usr/sbin/plymouth-set-default-theme" ]; then
	chroot "${rootfs}" /usr/sbin/plymouth-set-default-theme -R cybroidos \
		|| die "failed to set the Cybroid OS Plymouth theme"
fi

# --- Shared Xfce look --------------------------------------------------------
# The desktop ISO and pod-desktop consume the same rendered theme. Version and
# colours come from brand.toml only (no hardcoded version in this hook).
xfce_render="$(mktemp -d)"
trap 'rm -rf "${xfce_render}"' EXIT
python3 "${repo_root}/tools/render-xfce-brand.py" \
	--brand "${repo_root}/common/branding/brand.toml" \
	--out "${xfce_render}" >/dev/null
sh "${xfce_render}/install.sh" "${rootfs}" "${xfce_render}"

# --- Greeter configuration ---------------------------------------------------
for pair in \
	"${config_dir}/lightdm/lightdm-gtk-greeter.conf:/etc/lightdm/lightdm-gtk-greeter.conf" \
	"${config_dir}/lightdm/90-cybroidos.conf:/etc/lightdm/lightdm.conf.d/90-cybroidos.conf" \
	"${config_dir}/sddm/90-cybroidos.conf:/etc/sddm.conf.d/90-cybroidos.conf"; do
	src="${pair%%:*}"; dest="${pair##*:}"
	[ -f "${src}" ] || die "missing branding config: ${src}"
	mkdir -p "$(dirname "${rootfs}${dest}")"
	install -m 0644 "${src}" "${rootfs}${dest}"
done

# --- Quiet, branded boot ----------------------------------------------------
cat > "${rootfs}/etc/default/grub" <<'EOF'
# Generated by targets/server/hooks/apply-branding.sh from brand.toml.
GRUB_DEFAULT=0
GRUB_TIMEOUT=3
GRUB_DISTRIBUTOR="Cybroid OS"
GRUB_CMDLINE_LINUX_DEFAULT="quiet splash"
GRUB_CMDLINE_LINUX=""
GRUB_DISABLE_OS_PROBER=true
EOF

echo "Branding applied (wallpaper, LightDM/SDDM, Xfce, Plymouth, GRUB)"
