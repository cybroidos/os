#!/usr/bin/env bash
# Install the Cybroid OS server/pods runtime configuration into a rootfs:
# cloud-init NoCloud datasource + first-boot hygiene, SSH hardening, xrdp/Xfce,
# noVNC fallback, headless kcd and /etc/cybroidos/server.conf.
#
# Usage: configure-cloud-init.sh ROOTFS CONFIG_DIR VERSION HOSTNAME PUBKEY_FILE
set -euo pipefail

die() { printf 'error: %s\n' "$*" >&2; exit 1; }

[ "$#" -eq 5 ] || die "usage: $0 ROOTFS CONFIG_DIR VERSION HOSTNAME PUBKEY_FILE"
rootfs="$1"; config_dir="$2"; version="$3"; hostname="$4"; pubkey_file="$5"
[ -d "${rootfs}" ] || die "rootfs not found: ${rootfs}"
[ -d "${config_dir}" ] || die "config directory not found: ${config_dir}"
[ -f "${pubkey_file}" ] || die "SSH public key not found: ${pubkey_file}"

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
install_file() {
	# install_file SOURCE DESTINATION MODE — DESTINATION is rootfs-relative.
	local src="$1" dest="$2" mode="$3"
	[ -f "${src}" ] || die "missing config file: ${src}"
	mkdir -p "$(dirname "${rootfs}${dest}")"
	install -m "${mode}" "${src}" "${rootfs}${dest}"
}

echo "Configuring cloud-init and remote-access services in ${rootfs}"

# --- cloud-init: NoCloud first, never a network metadata service ------------
install_file "${config_dir}/cloud-init/90-cybroidos.cfg" \
	"/etc/cloud/cloud.cfg.d/90-cybroidos.cfg" "0644"

# --- First-boot hygiene (shared with the cloud-init user-data runcmd) -------
install_file "${here}/first-boot.sh" "/usr/bin/cybroidos-first-boot" "0755"
install_file "${config_dir}/systemd/cybroidos-first-boot.service" \
	"/etc/systemd/system/cybroidos-first-boot.service" "0644"

# --- Server configuration (shell-sourced by the launcher and first boot) ---
src="${config_dir}/server.conf"
[ -f "${src}" ] || die "missing config file: ${src}"
mkdir -p "${rootfs}/etc/cybroidos"
sed -e "s|__CYBROIDOS_VERSION__|${version}|g" \
	-e "s|__CYBROIDOS_HOSTNAME__|${hostname}|g" \
	"${src}" > "${rootfs}/etc/cybroidos/server.conf"
chmod 0644 "${rootfs}/etc/cybroidos/server.conf"

# --- Xfce session, xrdp (RDP) and noVNC (browser fallback) -----------------
install_file "${config_dir}/xfce-session" "/etc/cybroidos/xfce-session" "0755"
install_file "${config_dir}/systemd/cybroidos-xfce-session.service" \
	"/etc/systemd/system/cybroidos-xfce-session.service" "0644"
install_file "${config_dir}/xrdp/xrdp.ini" "/etc/xrdp/xrdp.ini" "0644"
install_file "${config_dir}/xrdp/startwm.sh" "/etc/xrdp/startwm.sh" "0755"
install_file "${config_dir}/novnc/novnc.conf" "/etc/cybroidos/novnc.conf" "0644"

# --- SSH: public-key only, no root login, no default password ---------------
install_file "${config_dir}/sshd/90-cybroidos.conf" \
	"/etc/ssh/sshd_config.d/90-cybroidos.conf" "0644"
if ! chroot "${rootfs}" /bin/sh -c 'id cybroid' >/dev/null 2>&1; then
	chroot "${rootfs}" /usr/sbin/useradd -m -s /bin/bash \
		-G sudo,adm cybroid || die "failed to create the cybroid admin user"
fi
chroot "${rootfs}" /usr/bin/passwd -l cybroid >/dev/null \
	|| die "failed to lock the cybroid password (no default password allowed)"
printf '%s\n' "${hostname}" > "${rootfs}/etc/hostname"
printf '127.0.0.1 localhost %s\n' "${hostname}" > "${rootfs}/etc/hosts"

# --- kcd: headless KDE Connect for phone control (ADR-0004/0005) ------------
install_file "${config_dir}/systemd/cybroidos-kcd.service" \
	"/etc/systemd/system/cybroidos-kcd.service" "0644"
kcd_conf="${rootfs}/home/cybroid/.config/kcd/kcd.toml"
mkdir -p "$(dirname "${kcd_conf}")"
cat > "${kcd_conf}" <<EOF
# Generated by targets/server/hooks/configure-cloud-init.sh.
device_name = "${hostname}"
device_type = "desktop"
tcp_port = 1716
log_level = "info"
EOF
chown -R 1000:1000 "${rootfs}/home/cybroid/.config" 2>/dev/null || true

echo "Cloud-init, SSH hardening, Xfce/RDP/noVNC and kcd configured"
