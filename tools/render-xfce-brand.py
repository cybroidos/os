#!/usr/bin/env python3
"""Render the shared Cybroid OS Xfce theme from common/branding/brand.toml.

Every target that ships Xfce (desktop ISO, server qcow2, pod-desktop) consumes
the output of this script. The version and all brand values come from the single
source of truth; no version or colour is hardcoded here.

Usage: render-xfce-brand.py --brand common/branding/brand.toml --out DIR
"""

from __future__ import annotations

import argparse
import html
import shlex
import shutil
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--brand", required=True, type=Path, help="path to brand.toml")
    parser.add_argument("--release", default="trixie", help="suite for the generated metadata")
    parser.add_argument("--out", required=True, type=Path, help="output directory")
    args = parser.parse_args()

    import tomllib

    data = tomllib.loads(args.brand.read_text(encoding="utf-8"))
    ident = data["identity"]
    colors = data["colors"]
    assets = data["assets"]

    name = ident["name"]
    version = ident["version"]  # single source of truth — never hardcode a version
    vendor = ident["vendor"]

    args.out.mkdir(parents=True, exist_ok=True)
    brand_root = args.brand.resolve().parent

    def esc(value: str) -> str:
        return html.escape(str(value), quote=True)

    # Brand values used by install.sh; shlex-quoted so shell sourcing is safe.
    env = {
        "PRODUCT_NAME": name,
        "PRODUCT_VERSION": version,
        "VENDOR_NAME": vendor,
        "BACKGROUND_COLOR": colors["background"],
        "PRIMARY_COLOR": colors["primary"],
        "ACCENT_COLOR": colors["accent"],
    }
    (args.out / "brand.env").write_text(
        "".join(f"{key}={shlex.quote(str(value))}\n" for key, value in env.items()),
        encoding="utf-8",
    )

    # Branded wallpaper shared by the whole Xfce look (also usable by Plasma).
    (args.out / "wallpaper.svg").write_text(
        f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/render-xfce-brand.py from {esc(args.brand.name)}. -->
<svg xmlns="http://www.w3.org/2000/svg" width="1920" height="1080" viewBox="0 0 1920 1080">
  <defs>
    <linearGradient id="cybroid-xfce-gradient" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="{esc(colors['primary'])}"/>
      <stop offset="0.55" stop-color="{esc(colors['primary_deep'])}"/>
      <stop offset="1" stop-color="{esc(colors['background'])}"/>
    </linearGradient>
    <linearGradient id="cybroid-xfce-rule" x1="0" y1="0" x2="1" y2="0">
      <stop offset="0" stop-color="{esc(colors['accent_alt'])}"/>
      <stop offset="1" stop-color="{esc(colors['accent'])}"/>
    </linearGradient>
  </defs>
  <rect width="1920" height="1080" fill="url(#cybroid-xfce-gradient)"/>
  <circle cx="1580" cy="210" r="420" fill="{esc(colors['accent'])}" opacity="0.10"/>
  <circle cx="280" cy="920" r="360" fill="{esc(colors['accent_alt'])}" opacity="0.10"/>
  <text x="960" y="500" text-anchor="middle" fill="{esc(colors['foreground'])}"
        font-family="sans-serif" font-size="110" letter-spacing="6">{esc(name)}</text>
  <rect x="660" y="552" width="600" height="8" rx="4" fill="url(#cybroid-xfce-rule)"/>
  <text x="960" y="620" text-anchor="middle" fill="{esc(colors['accent'])}"
        font-family="sans-serif" font-size="34">{esc(vendor)}</text>
  <text x="960" y="1000" text-anchor="middle" fill="{esc(colors['foreground'])}" opacity="0.7"
        font-family="sans-serif" font-size="22">{esc(ident['support_url'])}</text>
</svg>
""",
        encoding="utf-8",
    )

    (args.out / "xfce4-desktop.xml").write_text(
        """<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/render-xfce-brand.py from brand.toml. -->
<channel name="xfce4-desktop" version="1.0">
  <property name="backdrop" type="empty">
    <property name="screen0" type="empty">
      <property name="monitor0" type="empty">
        <property name="workspace0" type="empty">
          <property name="image-style" type="int" value="5"/>
          <property name="image-path" type="string" value="/usr/share/backgrounds/cybroidos/cybroidos-wallpaper.png"/>
          <property name="last-image" type="string" value="/usr/share/backgrounds/cybroidos/cybroidos-wallpaper.png"/>
        </property>
      </property>
    </property>
  </property>
</channel>
""",
        encoding="utf-8",
    )

    (args.out / "gtk.css").write_text(
        f"""/* Generated by tools/render-xfce-brand.py — {esc(name)} {esc(version)}. */
@import url("/usr/share/themes/Adwaita/gtk-3.0/gtk.css");

@define-color theme_selected_bg_color {esc(colors['accent'])};
@define-color theme_selected_fg_color {esc(colors['on_accent'])};
@define-color cybroid_primary {esc(colors['primary'])};
@define-color cybroid_accent {esc(colors['accent'])};

#cybroid-brand-bar {{
  background-color: @cybroid_primary;
  color: {esc(colors['foreground'])};
}}
""",
        encoding="utf-8",
    )

    (args.out / "cybroidos-xfce.desktop").write_text(
        f"""[Desktop Entry]
Type=Application
Name={esc(name)} Xfce
Comment=Branded Xfce session for {esc(name)} {esc(version)}
Exec=/usr/bin/cybroidos-xfce-session
TryExec=/usr/bin/startxfce4
DesktopNames=XFCE
X-LightDM-DesktopName={esc(name)} Xfce
X-KDE-PluginInfo-Version={esc(version)}
""",
        encoding="utf-8",
    )

    media = {
        "CYBROID_MEDIA_PROFILE": "1",
        "USE_COMPOSITING": "false",
        "DISABLE_SCREENSAVER": "true",
        "XFCE_SESSION_BIN": "/usr/bin/startxfce4",
        "X11VNC_EXTRA_ARGS": "-nowf -ncache 10 -ncache_cr",
    }
    (args.out / "xfce-media.conf").write_text(
        f"# Generated from brand.toml by tools/render-xfce-brand.py "
        f"({esc(name)} {esc(version)} / {esc(args.release)}).\n"
        + "".join(f"{key}={shlex.quote(str(value))}\n" for key, value in media.items()),
        encoding="utf-8",
    )

    # Static helpers live beside the brand source so they are versioned with it.
    static_root = Path(__file__).resolve().parent.parent / "common" / "branding" / "xfce"
    for helper in ("install.sh", "xfce-session-wrapper"):
        source = static_root / helper
        if not source.is_file():
            raise SystemExit(f"missing Xfce helper: {source}")
        shutil.copy2(source, args.out / helper)
        (args.out / helper).chmod(0o755)

    for key, target_name in (("logo_png", "logo.png"), ("mark_png", "mark.png")):
        source = brand_root / assets[key]
        if not source.is_file():
            raise SystemExit(f"missing brand asset: {source}")
        shutil.copy2(source, args.out / target_name)

    print(f"rendered Xfce branding into {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
