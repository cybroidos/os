#!/bin/sh
# Install the rendered Cybroid OS Xfce look into a target root filesystem.
#
# Usage: install.sh DEST_DIR SOURCE_DIR
#   DEST_DIR   "/" for a live chroot/container, or an offline rootfs path
#   SOURCE_DIR output of tools/render-xfce-brand.py
#
# Kept under common/branding/xfce so the desktop ISO, server image and pod
# desktop all ship the same theme. No version is hardcoded here: brand.env is
# generated from common/branding/brand.toml by the renderer.
set -eu

dest="${1:?usage: install.sh DEST_DIR SOURCE_DIR}"
src="${2:?usage: install.sh DEST_DIR SOURCE_DIR}"
[ -d "${dest}" ] || { echo "install-xfce: missing destination ${dest}" >&2; exit 1; }
[ -d "${src}" ] || { echo "install-xfce: missing source ${src}" >&2; exit 1; }
# shellcheck disable=SC1091  # generated by the renderer
. "${src}/brand.env"

wall_dir="${dest}/usr/share/backgrounds/cybroidos"
xfconf_dir="${dest}/etc/xdg/xfce4/xfconf/xfce-perchannel-xml"
theme_dir="${dest}/usr/share/cybroidos/xfce"

install -d "${wall_dir}" "${xfconf_dir}" "${theme_dir}" \
	"${dest}/usr/bin" "${dest}/usr/share/xsessions" \
	"${dest}/etc/skel/.config/gtk-3.0" "${dest}/etc/cybroidos"

# Branded wallpaper (SVG source plus a PNG for toolkits that need raster).
cp "${src}/wallpaper.svg" "${wall_dir}/wallpaper.svg"
wallpaper_png="${wall_dir}/cybroidos-wallpaper.png"
if command -v magick >/dev/null 2>&1; then
	magick -size 1920x1080 "xc:${BACKGROUND_COLOR}" "${src}/logo.png" \
		-gravity center -composite "${wallpaper_png}"
elif command -v convert >/dev/null 2>&1; then
	convert -size 1920x1080 "xc:${BACKGROUND_COLOR}" "${src}/logo.png" \
		-gravity center -composite "${wallpaper_png}"
else
	# ImageMagick is optional in minimal build containers: use the mark itself.
	cp "${src}/mark.png" "${wallpaper_png}"
fi

# Xfce desktop backdrop and GTK accent theme.
cp "${src}/xfce4-desktop.xml" "${xfconf_dir}/xfce4-desktop.xml"
cp "${src}/gtk.css" "${theme_dir}/gtk.css"
cp "${src}/gtk.css" "${dest}/etc/skel/.config/gtk-3.0/gtk.css"
if [ -d "${dest}/home/cybroid" ]; then
	install -d -o 1000 -g 1000 "${dest}/home/cybroid/.config/gtk-3.0"
	cp "${src}/gtk.css" "${dest}/home/cybroid/.config/gtk-3.0/gtk.css"
fi
skel_xfconf="${dest}/etc/skel/.config/xfce4/xfconf/xfce-perchannel-xml"
install -d "${skel_xfconf}"
cp "${src}/xfce4-desktop.xml" "${skel_xfconf}/xfce4-desktop.xml"
if [ -d "${dest}/home/cybroid" ]; then
	home_xfconf="${dest}/home/cybroid/.config/xfce4/xfconf/xfce-perchannel-xml"
	install -d -o 1000 -g 1000 "${home_xfconf}"
	cp "${src}/xfce4-desktop.xml" "${home_xfconf}/xfce4-desktop.xml"
fi

# Session entry, tuned launcher and media profile.
install -m 0644 "${src}/cybroidos-xfce.desktop" \
	"${dest}/usr/share/xsessions/cybroidos-xfce.desktop"
install -m 0755 "${src}/xfce-session-wrapper" \
	"${dest}/usr/bin/cybroidos-xfce-session"
install -m 0644 "${src}/xfce-media.conf" "${dest}/etc/cybroidos/xfce-media.conf"

echo "install-xfce: branded Xfce session installed into ${dest}"
