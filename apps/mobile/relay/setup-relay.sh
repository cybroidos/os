#!/usr/bin/env bash
# Generate WireGuard keypairs and v0 relay configs. Placeholder values must be
# reviewed by the operator; firewall/NAT/port forwarding are not configured.
set -euo pipefail

out_dir="${1:-./generated}"

if ! command -v wg >/dev/null 2>&1; then
	echo "error: 'wg' from wireguard-tools is required" >&2
	exit 1
fi

relay_addr="${RELAY_VPN_ADDRESS:-10.99.0.1/24}"
peer_addr="${PEER_VPN_ADDRESS:-10.99.0.2/32}"
vpn_subnet="${VPN_SUBNET:-10.99.0.0/24}"
listen_port="${WG_LISTEN_PORT:-51820}"
endpoint="${WG_ENDPOINT:-relay.example.invalid:51820}"
lan_subnet="${LAN_SUBNET:-192.168.1.0/24}"

case "${listen_port}" in
	'' | *[!0-9]*)
		echo "error: WG_LISTEN_PORT must be numeric" >&2
		exit 1
		;;
esac

umask 077
mkdir -p "${out_dir}"

relay_private="$(wg genkey)"
relay_public="$(printf '%s' "${relay_private}" | wg pubkey)"
peer_private="$(wg genkey)"
peer_public="$(printf '%s' "${peer_private}" | wg pubkey)"
trap 'unset relay_private peer_private' EXIT

relay_config="${out_dir}/wg0.conf"
peer_config="${out_dir}/cybroid-phone.conf"

cat >"${relay_config}" <<EOF
# Generated by setup-relay.sh (v0 skeleton). File mode 0600.
[Interface]
Address = ${relay_addr}
ListenPort = ${listen_port}
PrivateKey = ${relay_private}
# Firewall/NAT and upstream port forwarding are operator-managed.

[Peer]
PublicKey = ${peer_public}
AllowedIPs = ${peer_addr}
PersistentKeepalive = 25
EOF

cat >"${peer_config}" <<EOF
# Generated by setup-relay.sh (v0 skeleton). File mode 0600.
[Interface]
Address = ${peer_addr}
PrivateKey = ${peer_private}
DNS = <DNS_SERVER_PLACEHOLDER>

[Peer]
PublicKey = ${relay_public}
Endpoint = ${endpoint}
AllowedIPs = ${vpn_subnet}, ${lan_subnet}
PersistentKeepalive = 25
EOF

chmod 0600 "${relay_config}" "${peer_config}"

echo "wrote ${relay_config} and ${peer_config} with mode 0600"
echo "relay public key: ${relay_public}"
echo "phone public key: ${peer_public}"
echo "next: review the configs, set firewall/port forwarding, enable wg-quick@wg0,"
echo "      and distribute ${peer_config} securely. No keys were printed."
